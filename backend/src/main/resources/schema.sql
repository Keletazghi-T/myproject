CREATE TABLE IF NOT EXISTS accounts (
    email VARCHAR(255) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author VARCHAR(255) NOT NULL,
    text VARCHAR(4000) NOT NULL
);

CREATE TABLE IF NOT EXISTS meetings (
    id VARCHAR(36) PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    meeting_date VARCHAR(30) NOT NULL,
    meeting_time VARCHAR(30) NOT NULL,
    duration VARCHAR(50) NOT NULL,
    platform VARCHAR(50) NOT NULL,
    link VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audience VARCHAR(255) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    link VARCHAR(500) NOT NULL
);
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS password_hashed BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE meetings ADD COLUMN IF NOT EXISTS join_url VARCHAR(2000);

ALTER TABLE comments ADD COLUMN IF NOT EXISTS parent_id BIGINT;
ALTER TABLE comments ADD CONSTRAINT IF NOT EXISTS comments_parent_fk FOREIGN KEY (parent_id) REFERENCES comments(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS comments_parent_index ON comments(parent_id);

ALTER TABLE accounts ADD COLUMN IF NOT EXISTS member_id UUID DEFAULT RANDOM_UUID() NOT NULL;
ALTER TABLE accounts ADD CONSTRAINT IF NOT EXISTS accounts_member_id_unique UNIQUE (member_id);
CREATE TABLE IF NOT EXISTS direct_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id UUID NOT NULL REFERENCES accounts(member_id) ON DELETE CASCADE,
    recipient_id UUID NOT NULL REFERENCES accounts(member_id) ON DELETE CASCADE,
    text VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS messages_pair_index ON direct_messages(sender_id, recipient_id, id);

